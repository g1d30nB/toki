"""
Turns Baloo 2 into the robot's smooth fonts (Gideon, 15 Oct: all of Toki's text
in Baloo 2, to match the cute face). M5GFX draws VLW fonts anti-aliased: a
header, one record per glyph, then each glyph's 8-bit alpha bitmap.

  uv run --with pillow python firmware/fonts/make-vlw.py

writes firmware/toki/fonts_baloo.h. Never edit that by hand; change the list
below and run this again. Printable ASCII only: the robot's text is English.

Sizes match the fonts they replace (capital heights): 28 px for FreeSans 12 pt
(buttons, titles, lines), 22 px for FreeMono 12 pt and FreeSans 9 pt (the label,
the approval hint, text that has to shrink to fit).
"""

import struct
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).parent
TTF = HERE / "Baloo2[wght].ttf"
OUT = HERE.parent / "toki" / "fonts_baloo.h"
PRINTABLE = "".join(chr(c) for c in range(0x20, 0x7F))
FONTS = [
    ("kBalooBold28", "Bold", 28, PRINTABLE),
    ("kBalooMedium28", "Medium", 28, PRINTABLE),
    ("kBalooBold22", "Bold", 22, PRINTABLE),
    ("kBalooMedium22", "Medium", 22, PRINTABLE),
    ("kBalooDigits54", "Bold", 54, "0123456789"),  # the pairing code
]


def vlw(weight: str, size: int, chars: str) -> bytes:
    font = ImageFont.truetype(str(TTF), size)
    font.set_variation_by_name(weight.encode())
    ascent, descent = font.getmetrics()
    records, bitmaps = [], []
    for ch in sorted(chars):  # M5GFX looks glyphs up by binary search
        code = ord(ch)
        advance = round(font.getlength(ch))
        if ch == " ":
            records.append((code, 0, 0, advance, 0, 0))
            continue
        pad = size
        img = Image.new("L", (size * 3, size * 3), 0)
        ImageDraw.Draw(img).text((pad, pad + ascent), ch, font=font, fill=255, anchor="ls")
        box = img.getbbox()
        if not box:
            records.append((code, 0, 0, advance, 0, 0))
            continue
        glyph = img.crop(box)
        w, h = glyph.size
        records.append((code, h, w, advance, (pad + ascent) - box[1], box[0] - pad))
        bitmaps.append(glyph.tobytes())
    # Ascent and descent from the glyphs themselves, not the font's line metrics: Baloo's
    # leave room for Devanagari, which would push every line 8 px lower than the
    # simulator (which places text by the tallest and deepest printable glyphs).
    ascent = max(dy for _, h, w, _, dy, _ in records if h)
    descent = max(h - dy for _, h, w, _, dy, _ in records if h)
    head = struct.pack(">6i", len(records), 11, size, 0, ascent, descent)
    body = b"".join(struct.pack(">7i", u, h, w, adv, dy, dx, 0) for u, h, w, adv, dy, dx in records)
    return head + body + b"".join(bitmaps)


def main():
    parts = [
        "// Generated by firmware/fonts/make-vlw.py from Baloo 2 (SIL Open Font License 1.1,",
        "// firmware/fonts/OFL.txt). Never edit by hand.",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    total = 0
    for name, weight, size, chars in FONTS:
        data = vlw(weight, size, chars)
        total += len(data)
        rows = [", ".join(f"0x{b:02x}" for b in data[i : i + 24]) for i in range(0, len(data), 24)]
        parts.append(f"// Baloo 2 {weight}, {size} px: {len(data)} bytes")
        parts.append(f"static const uint8_t {name}[] = {{\n  " + ",\n  ".join(rows) + "\n};\n")
        print(f"{name}: {len(data)} bytes")
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT.relative_to(HERE.parent.parent)} ({total // 1024} KB of font)")


main()
