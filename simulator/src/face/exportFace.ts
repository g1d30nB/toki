// Turns the simulator's face definition (tokens, expressions, palette, state
// tokens) into a C++ header for the firmware, so the browser stays the single
// source of truth: tune in the Face lab, export, flash. Run with
// `npm run export-face`; a test fails if the committed header is out of date.

import { defaultConfig } from "../state/agentState";
import { expressionIds, expressions, type Expression, type ManpuKind } from "./expressions";
import { palette } from "./palette";
import { defaultTokens } from "./tokens";

const SHAPES = ["round", "arc", "line", "sparkle", "spiral", "star", "sleep"] as const;
const GAZES = ["still", "scan", "dart", "scroll-up", "look-around", "follow-www"] as const;
const MOUTHS = ["none", "line", "smile", "o", "pout", "tongue", "wobble", "yawn", "open", "blep", "cat", "shout", "hmm"] as const;
const MANPU: ManpuKind[] = ["dots", "sweat", "magnifier", "www", "sparkles", "blush", "zzz", "question"];

const camel = (s: string) => s.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
const pascal = (s: string) => camel(s).replace(/^\w/, (c) => c.toUpperCase());
const num = (n: number) => (Number.isInteger(n) ? `${n}.0f` : `${n}f`);

function enumBlock(name: string, values: readonly string[]) {
  return `enum class ${name} : uint8_t { ${values.map(pascal).join(", ")} };`;
}

function expressionLiteral(id: string, e: Expression) {
  const manpu = e.manpu.length ? e.manpu.map((m) => `Manpu_${pascal(m)}`).join(" | ") : "0";
  const intro = e.intro ? `EyeShape::${pascal(e.intro.shape)}, ${e.intro.ms}` : `EyeShape::${pascal(e.shape)}, 0`;
  return [
    `  /* ${id} */ {`,
    `    EyeShape::${pascal(e.shape)}, ${intro},`,
    `    ${num(e.scale)}, ${num(e.roundness)}, ${num(e.open)}, ${num(e.smile)}, ${num(e.squint)},`,
    `    {${num(e.pupil.x)}, ${num(e.pupil.y)}}, ${num(e.pupilScale)}, ${num(e.highlight)},`,
    `    Gaze::${pascal(e.gaze)},`,
    `    {${num(e.brows.y)}, ${num(e.brows.angle)}, ${num(e.brows.tilt)}, ${num(e.brows.len ?? 1)}, ${num(e.brows.curve ?? -1)}},`,
    `    Mouth::${pascal(e.mouth)}, ${num(e.mouthShift)},`,
    `    ${manpu},`,
    `    ${num(e.blinkRate)}, ${num(e.blinkSoftness)}, ${e.busy}, ${num(e.slide)},`,
    `    ${num(e.cheeks)}, ${e.lashes}, ${num(e.lidTilt)},`,
    `  },`,
  ].join("\n");
}

export function exportFaceHeader(): string {
  const tokenKeys = Object.keys(defaultTokens) as (keyof typeof defaultTokens)[];
  const configKeys = Object.keys(defaultConfig) as (keyof typeof defaultConfig)[];
  const lines: string[] = [];
  lines.push(
    "// GENERATED by simulator/src/face/exportFace.ts. Do not edit by hand:",
    "// tune in the simulator's Face lab, then run `npm --prefix simulator run export-face`.",
    "// Units: pixels at 320 x 240, milliseconds, BSP-independent.",
    "#pragma once",
    "#include <stdint.h>",
    "",
    "namespace toki {",
    "",
    "// Palette (RGB888; convert with color888 on the device).",
  );
  for (const [k, v] of Object.entries(palette)) lines.push(`constexpr uint32_t k${pascal(k)} = 0x${v.slice(1)};`);
  lines.push(
    "",
    enumBlock("EyeShape", SHAPES),
    enumBlock("Gaze", GAZES),
    enumBlock("Mouth", MOUTHS),
    "",
    "// Manpu are a bitmask: an expression can show several.",
    ...MANPU.map((m, i) => `constexpr uint16_t Manpu_${pascal(m)} = 1u << ${i};`),
    "",
    "struct Tokens {",
    ...tokenKeys.map((k) => `  float ${k};`),
    "};",
    "",
    "constexpr Tokens kTokens = {",
    ...tokenKeys.map((k) => `  ${num(defaultTokens[k])}, // ${k}`),
    "};",
    "",
    "// Agent-state tokens (simulator/src/state/agentState.ts).",
    "struct StateConfig {",
    ...configKeys.map((k) => `  float ${k};`),
    "};",
    "",
    "constexpr StateConfig kStateConfig = {",
    ...configKeys.map((k) => `  ${num(defaultConfig[k])}, // ${k}`),
    "};",
    "",
    "struct Vec2 { float x, y; };",
    "struct Brows { float y, angle, tilt, len, curve; };  // curve -1: the browCurve token",
    "",
    "struct Expression {",
    "  EyeShape shape;",
    "  EyeShape introShape; // shown first for introMs (0 = none)",
    "  uint16_t introMs;",
    "  float scale, roundness, open, smile, squint;",
    "  Vec2 pupil;",
    "  float pupilScale, highlight;",
    "  Gaze gaze;",
    "  Brows brows;",
    "  Mouth mouth;",
    "  float mouthShift;",
    "  uint16_t manpu;",
    "  float blinkRate, blinkSoftness;",
    "  bool busy;",
    "  float slide;",
    "  float cheeks;  // kawaii pass: pink cheek size, 0 none",
    "  bool lashes;   // three lashes on closed eyes",
    "  float lidTilt; // degrees the top lid slants down towards the nose (a scowl)",
    "};",
    "",
    `enum class ExpressionId : uint8_t { ${expressionIds.map(pascal).join(", ")}, Count };`,
    "",
    `constexpr const char* kExpressionNames[] = { ${expressionIds.map((id) => `"${id}"`).join(", ")} };`,
    "",
    "constexpr Expression kExpressions[] = {",
    ...expressionIds.map((id) => expressionLiteral(id, expressions[id] as Expression)),
    "};",
    "",
    "}  // namespace toki",
    "",
  );
  return lines.join("\n");
}
